#!/usr/bin/env node
/**
 * spring-easing.mjs — generate CSS `linear()` easing strings from Apple spring parameters.
 *
 * Apple's own model (SwiftUI Spring(duration:bounce:), WWDC23 "Animate with springs"):
 *   omega0 = 2*PI / duration          (undamped angular frequency; duration = "response")
 *   zeta   = bounce >= 0 ? 1 - bounce : 1 / (1 + bounce)
 * which reproduces the documented sample: Spring(duration: 0.5, bounce: 0.3)
 *   -> mass 1, stiffness 157.9, damping 17.6   (omega0 = sqrt(157.9) = 12.566 = 2*PI/0.5, zeta = 17.6/(2*12.566) = 0.70)
 *
 * A damped spring is not a cubic-bezier, so it cannot be expressed as one. CSS `linear()`
 * can: it accepts an arbitrary list of stops and output values outside [0,1], which is
 * exactly what an overshooting spring needs.
 *
 * Usage:
 *   node scripts/spring-easing.mjs                     # print the four token easings
 *   node scripts/spring-easing.mjs --bounce .2 --response .35
 *   node scripts/spring-easing.mjs --css               # print a :root token block
 */

const PI = Math.PI;

/** Position of a unit spring released from rest at 0 toward 1. */
export function springPosition(t, response, bounce) {
  const w0 = (2 * PI) / response;
  const zeta = bounce >= 0 ? 1 - bounce : 1 / (1 + bounce);
  if (zeta >= 0.999) {
    // critically damped: no overshoot
    return 1 - Math.exp(-w0 * t) * (1 + w0 * t);
  }
  const z = Math.min(zeta, 0.999);
  const wd = w0 * Math.sqrt(1 - z * z);
  return 1 - Math.exp(-z * w0 * t) * (Math.cos(wd * t) + ((z * w0) / wd) * Math.sin(wd * t));
}

/** Time after which the spring stays within `eps` of its target. */
export function settleTime(response, bounce, eps = 0.0015) {
  const step = response / 400;
  let last = 0;
  for (let t = 0; t < response * 8; t += step) {
    if (Math.abs(1 - springPosition(t, response, bounce)) > eps) last = t;
  }
  return last + step;
}

/** Build the CSS easing function. Stops are evenly spaced; first = 0, last = 1. */
export function springEasing({ bounce = 0.15, response = 0.4, points = 26, precision = 3 } = {}) {
  const duration = settleTime(response, bounce);
  const out = [];
  for (let i = 0; i < points; i++) {
    const p = i / (points - 1);
    const v = i === 0 ? 0 : i === points - 1 ? 1 : springPosition(p * duration, response, bounce);
    out.push(Number(v.toFixed(precision)));
  }
  return {
    css: 'linear(' + out.join(', ') + ')',
    durationMs: Math.round(duration * 1000),
    bounce,
    response,
    peak: Math.max(...out),
  };
}

export const PRESETS = {
  // Tuned so every preset settles inside Apple's 300-500ms window and the
  // overshoot stays subtle: peak 1.015 / 1.000 / 1.038 / 1.002.
  // name              bounce  response  use
  'ap-spring-snappy': { bounce: 0.2, response: 0.25, use: 'press feedback, button release, small controls' },
  'ap-spring-smooth': { bounce: 0.05, response: 0.3, use: 'hover lift, nav, generic state change' },
  'ap-spring-bouncy': { bounce: 0.28, response: 0.3, use: 'modal/sheet enter, toggle knob, pop-in' },
  'ap-spring-gentle': { bounce: 0.1, response: 0.4, use: 'reveal-on-scroll, expanding panels' },
};

function fmt(v, n = 3) {
  const s = Number(v.toFixed(n)).toString();
  return s;
}

function main(argv) {
  const flag = (name, fallback) => {
    const i = argv.indexOf('--' + name);
    return i >= 0 && argv[i + 1] !== undefined ? Number(argv[i + 1]) : fallback;
  };
  const bounce = flag('bounce', null);
  const response = flag('response', null);

  if (bounce !== null || response !== null) {
    const e = springEasing({ bounce: bounce ?? 0.15, response: response ?? 0.4, points: flag('points', 26) });
    console.log(e.css);
    console.error('# duration: ' + e.durationMs + 'ms  peak: ' + fmt(e.peak));
    return;
  }

  if (argv.includes('--css')) {
    console.log('/* generated by scripts/spring-easing.mjs — do not hand-edit */');
    console.log(':root {');
    for (const [name, p] of Object.entries(PRESETS)) {
      const e = springEasing({ bounce: p.bounce, response: p.response });
      console.log('  --' + name + ': ' + e.css + ';');
      console.log('  --' + name + '-dur: ' + e.durationMs + 'ms;   /* ' + p.use + ' */');
    }
    console.log('}');
    return;
  }

  for (const [name, p] of Object.entries(PRESETS)) {
    const e = springEasing({ bounce: p.bounce, response: p.response });
    console.log(name.padEnd(18) + ' bounce ' + p.bounce + '  response ' + p.response + 's  ->  ' + e.durationMs + 'ms  peak ' + fmt(e.peak, 4));
    console.log('  ' + e.css);
    console.log('');
  }
}

if (import.meta.url === 'file:///' + process.argv[1].replace(/\\/g, '/')) main(process.argv.slice(2));
